import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import org.jetbrains.kotlin.gradle.tasks.KotlinJvmCompile

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.android.kotlin.multiplatform.library)
    alias(libs.plugins.kotlin.compose)
}

val generateNotices = tasks.register("generateNotices") {
    val out = layout.buildDirectory.dir("generated/notices")
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("com/tmplayer/ui/about").apply { mkdirs() }
        dir.resolve("NoticesSource.kt").writeText(
            "package com.tmplayer.ui.about\n\n" +
                "/** Generated by :ui's generateNotices. */\n" +
                "internal object NoticesSource {\n" +
                "    const val TEXT: String = \"# Third-Party Notices\\n\\nMWPlayer uses open-source libraries including TDLib, AndroidX Media3, and Jetpack Compose.\\n\"\n" +
                "}\n",
        )
    }
}

kotlin {
    android {
        namespace = "com.tmplayer.ui"
        compileSdk = 37
        minSdk = 23
    }
    sourceSets {
        commonMain {
            kotlin.srcDir(generateNotices)
        }
        commonMain.dependencies {
            api(project(":core"))
            api(libs.androidx.lifecycle.viewmodel)
        }
        androidMain {
            kotlin.srcDir("src/shared/kotlin")
            dependencies {
                implementation(project.dependencies.platform(libs.androidx.compose.bom))
                api(libs.androidx.compose.ui)
                api(libs.androidx.compose.foundation)
                api(libs.androidx.compose.material3)
                implementation(libs.androidx.activity.compose)
                implementation(libs.zxing.core)
            }
        }
    }
}

tasks.withType<KotlinJvmCompile>().configureEach {
    compilerOptions.jvmTarget.set(JvmTarget.JVM_17)
}
tasks.withType<JavaCompile>().configureEach {
    sourceCompatibility = "17"
    targetCompatibility = "17"
}

composeCompiler {
    stabilityConfigurationFiles.add(rootProject.layout.projectDirectory.file("compose-stability.conf"))
}
